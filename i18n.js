/**
 * Site translations: Portuguese is the page itself; English and Chinese
 * replace text in the browser. Language: ?lang=pt|en|zh, then the visitor's
 * last choice, then Portuguese. Add ?i18n-check to list untranslated text in
 * the console. Generated dictionary below: each unit is [pt, en, zh], where pt
 * is the element's innerHTML with whitespace collapsed.
 */
(function () {
    const LANGS = ['pt', 'en', 'zh'];
    const HTML_LANG = { pt: 'pt-BR', en: 'en', zh: 'zh-CN' };
    const norm = (s) => s.replace(/\s+/g, ' ').trim();

    function chosen() {
        const q = new URLSearchParams(location.search).get('lang');
        if (LANGS.includes(q)) return q;
        try {
            const saved = localStorage.getItem('spec-architect-lang');
            if (LANGS.includes(saved)) return saved;
        } catch (e) { /* storage blocked: stay in Portuguese */ }
        return 'pt';
    }

    const lang = chosen();
    const col = LANGS.indexOf(lang);

    /** Translated string for app.js ({name} placeholders filled from vars). */
    window.t = function (key, vars) {
        const entry = I18N_DATA.strings[key];
        let s = entry ? entry[col] || entry[0] : key;
        Object.entries(vars || {}).forEach(([k, v]) => { s = s.replace(`{${k}}`, v); });
        return s;
    };
    window.siteLang = lang;

    function translatePage() {
        document.documentElement.lang = HTML_LANG[lang];
        document.querySelectorAll('[data-lang]').forEach((b) => {
            b.classList.toggle('on', b.dataset.lang === lang);
            b.setAttribute('aria-pressed', b.dataset.lang === lang ? 'true' : 'false');
            b.addEventListener('click', () => {
                try { localStorage.setItem('spec-architect-lang', b.dataset.lang); } catch (e) { /* ignore */ }
                const url = new URL(location.href);
                if (b.dataset.lang === 'pt') url.searchParams.delete('lang');
                else url.searchParams.set('lang', b.dataset.lang);
                location.href = url.toString();
            });
        });
        if (lang === 'pt') return;

        document.title = window.t('title');
        const desc = document.querySelector('meta[name="description"]');
        if (desc) desc.setAttribute('content', window.t('description'));

        const map = new Map(I18N_DATA.units.map((u) => [u[0], u[col]]));
        const missing = [];
        for (const el of document.body.querySelectorAll('*')) {
            if (['SCRIPT', 'STYLE', 'CODE'].includes(el.tagName) || el.closest('svg') || !el.isConnected) continue;
            const direct = [...el.childNodes].filter((n) => n.nodeType === 3 && norm(n.textContent));
            if (!direct.length) continue;
            if (el.querySelector('svg')) {
                direct.forEach((n) => {
                    const k = norm(n.textContent);
                    if (map.has(k)) n.textContent = ` ${map.get(k)} `;
                    else missing.push(k);
                });
                continue;
            }
            const k = norm(el.innerHTML);
            if (map.has(k)) el.innerHTML = map.get(k);
            else missing.push(k);
        }
        if (new URLSearchParams(location.search).has('i18n-check')) {
            console.log(`[i18n] ${lang}: sem tradução (ficam como estão):`, missing);
        }
    }

    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', translatePage);
    else translatePage();
})();
